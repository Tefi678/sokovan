def get_level(num):
    """Devuelve el nivel solicitado o el último disponible si te pasas"""
    if num in LEVEL_DATA:
        return LEVEL_DATA[num]
    # Si no existe el nivel exacto, busca el más cercano anterior
    available_levels = sorted(LEVEL_DATA.keys())
    closest = max([lvl for lvl in available_levels if lvl <= num])
    return LEVEL_DATA[closest]